package handler

import (
	"github.com/chihqiang/ten-go/core/cast"
	"net/http"

	"chihqiang/llm-gate/logic"

	"github.com/chihqiang/ten-go/rest"
)

type MenuHandler struct {
	svc *logic.MenuLogic
}

func NewMenuHandler(svc *logic.MenuLogic) *MenuHandler {
	return &MenuHandler{svc: svc}
}

func (h *MenuHandler) List(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	var req logic.MenuListRequest
	if err := rest.BindQuery(r, &req); err != nil {
		_ = rest.ErrorJSONCtx(r.Context(), w, rest.NewCodeError(rest.StatusOf(err), err.Error()))
		return
	}

	resp, err := h.svc.List(ctx, &req)
	if err != nil {
		rest.OkJSONCtx(ctx, w, rest.NewCodeError(rest.BusinessCodeError, err.Error()))
		return
	}

	rest.OkJSONCtx(ctx, w, resp)
}

func (h *MenuHandler) AllList(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	menus, err := h.svc.AllList(ctx)
	if err != nil {
		rest.OkJSONCtx(ctx, w, rest.NewCodeError(rest.BusinessCodeError, err.Error()))
		return
	}

	rest.OkJSONCtx(ctx, w, menus)
}

func (h *MenuHandler) Detail(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	id := cast.To[int64](rest.PathParam(r, "id"))
	if id <= 0 {
		rest.ErrorJSONCtx(ctx, w, rest.NewCodeError(http.StatusBadRequest, "无效的ID"))
		return
	}

	menu, err := h.svc.GetByID(ctx, id)
	if err != nil {
		rest.OkJSONCtx(ctx, w, rest.NewCodeError(rest.BusinessCodeError, err.Error()))
		return
	}

	rest.OkJSONCtx(ctx, w, menu)
}

